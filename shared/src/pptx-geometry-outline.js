const bands = {
  sng: [[-0.5, 0.5]],
  dbl: [
    [-0.5, -1 / 6],
    [1 / 6, 0.5],
  ],
  thinThick: [
    [-0.5, -0.3],
    [-0.1, 0.5],
  ],
  thickThin: [
    [-0.5, 0.1],
    [0.3, 0.5],
  ],
  tri: [
    [-0.5, -1 / 3],
    [-1 / 6, 1 / 6],
    [1 / 3, 0.5],
  ],
}
const fail = (reason) => {
  throw new RangeError(`Unsupported native outline: ${reason}`)
}
const equal = (a, b) => a.x === b.x && a.y === b.y
function supportsNativeOutline(stroke) {
  return (
    !!stroke &&
    Object.hasOwn(bands, stroke.compound) &&
    ['ctr', 'in'].includes(stroke.alignment) &&
    ['flat', 'rnd', 'sq'].includes(stroke.cap) &&
    dashPattern(stroke.dash) !== null &&
    (['round', 'bevel'].includes(stroke.join?.kind) ||
      (stroke.join?.kind === 'miter' &&
        Number.isInteger(stroke.join.limit) &&
        stroke.join.limit >= 0 &&
        stroke.join.limit <= 2147483647)) &&
    [stroke.headEnd, stroke.tailEnd].every((end) => end === undefined || end.type === 'none')
  )
}
// Coordinates are already rounded and budget-checked. Remove only vertices
// between exactly collinear neighbors; no tolerance or rescaling is involved.
function cleanIntegerBoundary(points) {
  const between = (a, b, c) => {
    const x = b.X - a.X, y = b.Y - a.Y
    const u = c.X - b.X, v = c.Y - b.Y
    const xv = x * v, yu = y * u
    // Integer products inside this bound are exact IEEE-754 integers. Typical
    // adjacent flattened vertices need no arbitrary-precision allocations.
    const collinear = Number.isSafeInteger(xv) && Number.isSafeInteger(yu)
      ? xv === yu
      : BigInt(x) * BigInt(v) === BigInt(y) * BigInt(u)
    if (!collinear) return false
    const xu = x * u, yv = y * v, along = xu + yv
    return Number.isSafeInteger(xu) && Number.isSafeInteger(yv) && Number.isSafeInteger(along)
      ? along >= 0
      : BigInt(x) * BigInt(u) + BigInt(y) * BigInt(v) >= 0n
  }
  const result = []
  for (const point of points) {
    if (result.length && result.at(-1).X === point.X && result.at(-1).Y === point.Y) continue
    while (result.length > 1 && between(result.at(-2), result.at(-1), point)) result.pop()
    result.push(point)
  }
  let start = 0
  while (result.length - start > 3) {
    if (between(result.at(-2), result.at(-1), result[start])) result.pop()
    else if (between(result.at(-1), result[start], result[start + 1])) start++
    else break
  }
  return start ? result.slice(start) : result
}
// Clipper's full-range flag depends on absolute coordinates, not adjacent
// differences. Keep its exact predicate without JSBN allocations when the
// products fit in a Number; use native BigInt for larger integer products.
function exactOutputSlopesEqual(a, b, c, useFullRange) {
  const x = a.X - b.X, y = a.Y - b.Y
  const u = b.X - c.X, v = b.Y - c.Y
  if (!Number.isSafeInteger(x) || !Number.isSafeInteger(y) ||
      !Number.isSafeInteger(u) || !Number.isSafeInteger(v))
    return Clipper.ClipperBase.SlopesEqual4(a, b, c, useFullRange)
  const left = y * u, right = x * v
  return Number.isSafeInteger(left) && Number.isSafeInteger(right)
    ? left === right
    : BigInt(y) * BigInt(u) === BigInt(x) * BigInt(v)
}
