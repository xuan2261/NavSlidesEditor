// Preserve the upstream linked-list walk, including the final starting vertex:
// changing that walk changes serialized contour hashes even for identical paint.
// PreserveCollinear/StrictlySimple retain the upstream between-point predicate;
// open outputs still use the untouched FixupOutPolyline method.
function fixupExactOutPolygon(outRec) {
  let lastOK = null
  outRec.BottomPt = null
  let point = outRec.Pts
  const preserveCollinear = this.PreserveCollinear || this.StrictlySimple
  for (;;) {
    if (point.Prev === point || point.Prev === point.Next) {
      outRec.Pts = null
      return
    }
    if (Clipper.IntPoint.op_Equality(point.Pt, point.Next.Pt) ||
        Clipper.IntPoint.op_Equality(point.Pt, point.Prev.Pt) ||
        (exactOutputSlopesEqual(point.Prev.Pt, point.Pt, point.Next.Pt, this.m_UseFullRange) &&
          (!preserveCollinear ||
            !this.Pt2IsBetweenPt1AndPt3(point.Prev.Pt, point.Pt, point.Next.Pt)))) {
      lastOK = null
      point.Prev.Next = point.Next
      point.Next.Prev = point.Prev
      point = point.Prev
    } else if (point === lastOK) break
    else {
      if (lastOK === null) lastOK = point
      point = point.Next
    }
  }
  outRec.Pts = point
}
function union(paths, fillType = Clipper.PolyFillType.pftNonZero) {
  const clipper = new Clipper.Clipper(),
    result = []
  // This instance-only adaptation is tied to the pinned upstream algorithm.
  // A dependency upgrade keeps stock behavior until its internals are reviewed.
  if (Clipper.version === '6.4.2.2') clipper.FixupOutPolygon = fixupExactOutPolygon
  clipper.AddPaths(paths.map(cleanIntegerBoundary), Clipper.PolyType.ptSubject, true)
  if (paths.length && !clipper.Execute(Clipper.ClipType.ctUnion, result, fillType, fillType))
    fail('coverage union')
  return result
}
function deriveNativeOutline(path, stroke, strokeWidth, { tolerance = 0.02, maxScale = 1 } = {}) {
  if (!supportsNativeOutline(stroke)) fail('profile')
  if (!Number.isFinite(strokeWidth) || strokeWidth < 0) fail('width')
  const transform = path.transform
  if (!Array.isArray(transform) || transform.length !== 6 || !transform.every(Number.isFinite))
    fail('transform')
  if (!(tolerance > 0 && tolerance <= 0.02 && Number.isFinite(maxScale) && maxScale >= 1))
    fail('error budget')
  // Frobenius norm is an upper bound on the affine linear part's largest singular value.
  const localTolerance = tolerance / (maxScale * Math.max(1, Math.hypot(...transform.slice(0, 4))))
  const scale = Math.max(1e6, 32 / localTolerance),
    subpaths = [],
    coverage = []
  const pattern = dashPattern(stroke.dash)
  // Authored join/cap tangents are exact; retain the conservative endpoint
  // flattening budget without making it depend on an unexercised miter limit.
  const sensitivity = 128
  const lengthBudget = pattern.length
    ? localTolerance / (8 * Math.max(1, path.segments.length))
    : Infinity
  const empty = {
    d: '',
    contours: [],
    bounds: null,
    transform: [...transform],
    fillRule: 'nonzero',
    errorBound: tolerance,
  }
  if (path.stroke === false || strokeWidth === 0) return empty
  let count = 0,
    current
  const check = (p) => {
    if (![p.x, p.y].every((n) => Number.isFinite(n) && Math.abs(n * scale) <= 2 ** 46))
      fail('coordinate budget')
  }
  const append = (p) => {
    check(p)
    if (!current.points.length || !equal(current.points.at(-1), p)) {
      if (++count > 131072) fail('point budget')
      current.points.push(p)
    }
  }
  for (const segment of path.segments) {
    segment.points.forEach(check)
    if (segment.kind === 'moveTo') {
      current = { points: [], closed: false, corners: new Set([0]), joins: new Map() }
      subpaths.push(current)
      append(segment.points[0])
    } else {
      if (!current || current.closed || !equal(current.points.at(-1), segment.points[0]))
        fail('subpath continuity')
      const start = current.points.length - 1
      flatten(segment, append, strokeWidth, localTolerance, sensitivity, lengthBudget)
      const end = current.points.length - 1
      if (end > start) {
        const [outgoing, incoming] = segmentTangents(segment)
        const curved = ['arcTo', 'quadBezTo', 'cubicBezTo'].includes(segment.kind)
        current.joins.set(start, { ...current.joins.get(start), outgoing, outgoingCurve: curved })
        current.joins.set(end, { ...current.joins.get(end), incoming, incomingCurve: curved })
      }
      current.corners.add(end)
      if (segment.kind === 'close') {
        closeSubpath(current, localTolerance)
      } else {
        current.firstSegment ??= segment
        current.lastSegment = segment
      }
    }
  }
  const integer = (p) => {
    check(p)
    return { X: Math.round(p.x * scale), Y: Math.round(p.y * scale) }
  }
  const integerPolygon = (polygon) => {
    count += polygon.length
    if (count > 786432) fail('coverage point budget')
    return polygon.map(integer)
  }
  const directional =
    stroke.alignment === 'in' || ['thinThick', 'thickThin'].includes(stroke.compound)
  for (const subpath of subpaths) {
    const { points, closed } = subpath
    if (points.length < 2) continue
    if (closed && directional) {
      const polygon = points.map(integer),
        area = Clipper.Clipper.Area(polygon),
        areaTolerance = scale * scale * localTolerance ** 2
      // Native CCW contours retain the signed normal, including outward
      // inset paint. Union normalizes orientation only for the simplicity check.
      const simple = union([polygon])
      if (area === 0 || simple.length !== 1 ||
          Math.abs(Math.abs(Clipper.Clipper.Area(simple[0])) - Math.abs(area)) > areaTolerance)
        fail('closed traversal or self-intersection')
    }
    for (const piece of dashSubpath(subpath, pattern, strokeWidth)) {
      const edges = piece.points.length < 2 ? [] : sweepEdges(piece)
      for (const interval of bands[stroke.compound]) {
        const swept = sweepBand(piece, edges, interval, stroke, strokeWidth, localTolerance)
        const polygons = swept.polygons.map(integerPolygon)
        // Resolve folded edge cells independently: a negative cell must not
        // erase another edge/join/cap even within the same authored dash.
        coverage.push(
          ...polygons,
          ...(swept.signedPolygons || []).flatMap((polygon) =>
            union([integerPolygon(polygon)], Clipper.PolyFillType.pftPositive)
          ),
          ...(swept.caps || []).map(integerPolygon)
        )
      }
    }
  }
  const result = union(coverage)
  if (result.reduce((sum, contour) => sum + contour.length, 0) > 786432) fail('union point budget')
  const contours = [], commands = []
  const bounds = [Infinity, Infinity, -Infinity, -Infinity]
  for (const integerContour of result) {
    const contour = [], pieces = []
    for (let i = 0; i < integerContour.length; i++) {
      const integerPoint = integerContour[i]
      const p = { x: integerPoint.X / scale, y: integerPoint.Y / scale }
      contour.push(p)
      bounds[0] = Math.min(bounds[0], p.x)
      bounds[1] = Math.min(bounds[1], p.y)
      bounds[2] = Math.max(bounds[2], p.x)
      bounds[3] = Math.max(bounds[3], p.y)
      pieces.push(`${i ? 'L' : 'M'} ${p.x} ${p.y}`)
    }
    contours.push(contour)
    commands.push(pieces.join(' ') + ' Z')
  }
  const d = commands.join(' ')
  return { ...empty, d, contours, bounds: contours.length ? bounds : null }
}
