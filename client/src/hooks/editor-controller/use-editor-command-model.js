import { useMemo } from 'react'

export function useEditorCommandModel({
  openTemplateModal,
  closeCommandPalette,
  groupElements,
  ungroupElements,
  save,
  zoomIn,
  zoomOut,
  fitZoom,
  startSlideshow,
  startSlideshowCurrent,
  insertLink,
  undo,
  redo,
  copy,
  cut,
  paste,
  duplicate,
  deleteSelection,
  selectAll,
  findReplace,
  timeline,
  speakerNotes,
  selectionPane,
  slideSorter,
  insertText,
  availability,
}) {
  return useMemo(
    () => [
      { id: 'insertSlide', label: 'Insert Slide', shortcut: 'Ctrl+M', action: openTemplateModal },
      { id: 'insertLink', label: 'Insert Link', shortcut: '', action: insertLink },
      { id: 'group', label: 'Group Elements', shortcut: 'Ctrl+G', action: groupElements },
      { id: 'ungroup', label: 'Ungroup Elements', shortcut: 'Ctrl+Shift+G', action: ungroupElements },
      { id: 'save', label: 'Save', shortcut: 'Ctrl+S', action: save },
      { id: 'zoomIn', label: 'Zoom In', shortcut: 'Ctrl+=', action: zoomIn },
      { id: 'zoomOut', label: 'Zoom Out', shortcut: 'Ctrl+-', action: zoomOut },
      { id: 'resetZoom', label: 'Fit to Window', shortcut: 'Ctrl+0', action: fitZoom },
      { id: 'startSlideshow', label: 'Start Slideshow', shortcut: 'F5', action: startSlideshow },
      { id: 'commandPalette', label: 'Command Palette', shortcut: 'Ctrl+K', action: closeCommandPalette },
      { id: 'undo', label: 'Undo', shortcut: 'Ctrl+Z', action: undo },
      { id: 'redo', label: 'Redo', shortcut: 'Ctrl+Y', action: redo },
      { id: 'copy', label: 'Copy', shortcut: 'Ctrl+C', action: copy },
      { id: 'cut', label: 'Cut', shortcut: 'Ctrl+X', action: cut },
      { id: 'paste', label: 'Paste', shortcut: 'Ctrl+V', action: paste },
      { id: 'duplicate', label: 'Duplicate', shortcut: 'Ctrl+D', action: duplicate },
      { id: 'deleteSelection', label: 'Delete', shortcut: 'Delete', action: deleteSelection },
      { id: 'selectAll', label: 'Select All', shortcut: 'Ctrl+A', action: selectAll },
      { id: 'findReplace', label: 'Find & Replace', shortcut: 'Ctrl+F', action: findReplace },
      { id: 'timeline', label: 'Animation Timeline', shortcut: '', action: timeline },
      { id: 'speakerNotes', label: 'Speaker Notes', shortcut: '', action: speakerNotes },
      { id: 'selectionPane', label: 'Selection Pane', shortcut: '', action: selectionPane },
      { id: 'slideSorter', label: 'Slide Sorter', shortcut: 'Ctrl+Shift+S', action: slideSorter },
      { id: 'insertText', label: 'Insert Text', shortcut: '', action: insertText },
      { id: 'startSlideshowCurrent', label: 'Start from Current Slide', shortcut: 'Shift+F5', action: startSlideshowCurrent },
    ].filter((command) => typeof command.action === 'function').map((command) => ({
      ...command,
      disabled: Boolean(availability?.[command.id]),
      disabledReason: availability?.[command.id],
    })),
    [
      openTemplateModal,
      closeCommandPalette,
      groupElements,
      ungroupElements,
      save,
      zoomIn,
      zoomOut,
      fitZoom,
      startSlideshow,
      startSlideshowCurrent,
      insertLink,
      undo,
      redo,
      copy,
      cut,
      paste,
      duplicate,
      deleteSelection,
      selectAll,
      findReplace,
      timeline,
      speakerNotes,
      selectionPane,
      slideSorter,
      insertText,
      availability,
    ]
  )
}
