import { test, expect } from '@playwright/test'
import { historyJourney, text, slide, content, quick, saved } from './helpers/p06-history-acceptance.js'

test('P06-07/08 deleted text Undo caret and locked master selection remain authorable', async ({ page, browser, request }, info) => {
  test.setTimeout(120000)
  await historyJourney({ page, browser, request }, info, ['P06-07', 'P06-08'], async ({ create, receipt }) => {
    const master = { id: 'master', name: 'Acceptance master', fixedElements: [{ ...text('brand', '<p>Master Alpha</p>'), locked: true }], placeholders: [] }
    const id = await create('P06 authoring acceptance', { slides: [slide([text('local', '<p>Local Alpha</p>')])], layoutMasters: [master] })
    await page.goto(`/editor/${id}`)
    await expect(content(page, 'local')).toContainText('Local Alpha')
    await content(page, 'local').click()
    await page.keyboard.press('Delete')
    await expect(content(page, 'local')).toHaveCount(0)
    await quick(page).getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(content(page, 'local')).toContainText('Local Alpha')
    await expect(page.locator('.ProseMirror')).toHaveCount(0)
    await content(page, 'local').dblclick()
    const editor = page.locator('.ProseMirror')
    await expect(editor).toContainText('Local Alpha')
    await editor.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.type('?')
    await expect(editor).toContainText('Local Alpha?')
    await page.keyboard.press('Escape')
    await saved(request, id, (deck) => deck.slides[0].elements[0].content, '<p>Local Alpha?</p>')
    receipt.runs.push({ scenarioId: 'P06-07', status: 'pending-identity', deletedTarget: 'local', restoredNextInput: '<p>Local Alpha?</p>', staleEditorCountAfterUndo: 0 })

    await page.getByRole('tab', { name: 'Design', exact: true }).click()
    await page.getByRole('button', { name: 'Open Layout Manager', exact: true }).click()
    await page.getByRole('button', { name: 'Edit master Acceptance master', exact: true }).click()
    await expect(page.getByTestId('statusbar-slide-position')).toHaveText('Editing master: Acceptance master')
    await content(page, 'brand').click()
    const x = page.getByTestId('prop-x')
    await expect(x).toHaveValue('100')
    await x.fill('222'); await x.blur()
    await expect(x).toHaveValue('222')
    await quick(page).getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(x).toHaveValue('100')
    await quick(page).getByRole('button', { name: 'Redo', exact: true }).click()
    await expect(x).toHaveValue('222')
    await saved(request, id, (deck) => ({ x: deck.layoutMasters[0].fixedElements[0].x, locked: deck.layoutMasters[0].fixedElements[0].locked, local: deck.slides[0].elements[0].content }), { x: 222, locked: true, local: '<p>Local Alpha?</p>' })
    await content(page, 'brand').click()
    await page.keyboard.press('Delete')
    await expect(content(page, 'brand')).toHaveCount(0)
    await expect(x).toHaveCount(0)
    await quick(page).getByRole('button', { name: 'Undo', exact: true }).click()
    await expect(content(page, 'brand')).toContainText('Master Alpha')
    await expect(x).toHaveCount(0)
    await content(page, 'brand').click()
    await expect(x).toHaveValue('222')
    await page.getByRole('button', { name: 'Exit master edit', exact: true }).click()
    await saved(request, id, (deck) => deck.layoutMasters[0].fixedElements[0].locked, true)
    await page.reload()
    await expect(content(page, 'local')).toContainText('Local Alpha?')
    receipt.runs.push({ scenarioId: 'P06-08', status: 'pending-identity', masterEditUndoRedoX: [222, 100, 222], survivingSelection: true, deletionClearsSelection: true, storedMasterLocked: true, localContentUnchanged: true })
  })
})
